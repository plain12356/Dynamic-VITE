"""Automatic commutator schedule for general models (2D lattices, fermions).

Generalises schedule.commutator_schedule (1D rings) in three ways:
  * symmetry: any group of qubit permutations that leaves H and H0 invariant (found automatically
    from candidate generators), instead of the dihedral group of a ring;
  * U(1) classes (merge_u1=True, for fermionic models): strings that differ only by X<->Y on the
    same sites are grouped, so that each layer conserves particle number (and every N_sigma); the
    projection of a U(1)-invariant C_n onto such a class is itself U(1)-invariant;
  * weights: a layer is the part of C_n in its class, with C_n's own coefficients (normalised).
    For spin models with permutation symmetry these coefficients are equal within an orbit, so the
    layer equals the unit-weight orbit sum up to a constant (which leaves VITE trajectories
    unchanged).
Ordering: by level, then (order="support") support weight, -|coefficient|, canonical key, or
(order="weight") -|coefficient| first.
"""
from __future__ import annotations
from dataclasses import dataclass
import itertools
import numpy as np
from .paulis import PauliSum, weight
from .ansatz import Layer
from .schedule import commutator


# ----------------------------------------------------------------------------- permutations
def permute_mask(m: int, perm) -> int:
    out = 0
    j = 0
    while m:
        if m & 1:
            out |= 1 << perm[j]
        m >>= 1
        j += 1
    return out


def permute_sum(P: PauliSum, perm) -> PauliSum:
    return PauliSum(P.n, [(c, permute_mask(x, perm), permute_mask(z, perm)) for c, x, z in P.items()])


def same(A: PauliSum, B: PauliSum, tol=1e-10) -> bool:
    keys = set(A.terms) | set(B.terms)
    return all(abs(A.terms.get(k, 0) - B.terms.get(k, 0)) < tol for k in keys)


def closure(gens, n):
    ident = tuple(range(n))
    group = {ident}
    frontier = [ident]
    while frontier:
        new = []
        for g in frontier:
            for h in gens:
                comp = tuple(h[g[i]] for i in range(n))
                if comp not in group:
                    group.add(comp)
                    new.append(comp)
        frontier = new
    return sorted(group)


def symmetry_group(H: PauliSum, H0: PauliSum, candidate_gens):
    """Group generated by the candidate permutations that leave both H and H0 invariant."""
    gens = [tuple(g) for g in candidate_gens if same(permute_sum(H, g), H) and same(permute_sum(H0, g), H0)]
    return closure(gens, H.n), gens


# ----------------------------------------------------------------------------- schedule
@dataclass
class Entry:
    level: int
    support: int
    weight: float
    key: tuple
    n_strings: int
    label: str


def _label(x, z, n):
    return "".join("I" if not (((x | z) >> j) & 1) else
                   ("X" if (x >> j) & 1 and not (z >> j) & 1 else ("Z" if not (x >> j) & 1 else "Y"))
                   for j in range(n))


def general_schedule(H: PauliSum, H0: PauliSum, group, *, merge_u1=False, max_layers=40, max_levels=8,
                     rel_tol=1e-9, return_entries=False, name_prefix="L", order="support",
                     grouping=None):
    """order='support' (lattices: locality first) or 'weight' (molecules: |coefficient| first).
    grouping: optional extra permutations (e.g. translations of an open chain) used only to group
    strings into layers; they need not be symmetries, since each layer keeps C_n's coefficients."""
    n = H.n

    grp = group if grouping is None else closure([tuple(g) for g in grouping] + list(group), n)

    def key_of(x, z):
        if merge_u1:
            z = z & ~x          # Y -> X: class of strings related by on-site U(1) rotations
        return min((permute_mask(x, g), permute_mask(z, g)) for g in grp)

    C = commutator(H, H0).scale(1j)
    seen = set()
    entries, layers = [], []
    for level in range(1, max_levels + 1):
        C = PauliSum(n, [(float(np.real(c)), x, z) for c, x, z in C.items() if abs(c) > 0])
        if len(C):
            cmax = max(abs(c) for c, _, _ in C.items())
            C = PauliSum(n, [(c / cmax, x, z) for c, x, z in C.items() if abs(c) > rel_tol * cmax])
        classes = {}
        for c, x, z in C.items():
            if bin(x & z).count("1") % 2 == 0:
                raise AssertionError("non-real generator in nested commutator")
            k = key_of(x, z)
            if k in seen:
                continue
            classes.setdefault(k, []).append((c, x, z))
        cw = lambda kv: -round(max(abs(c) for c, _, _ in kv[1]), 9)
        if order == "weight":
            ordered = sorted(classes.items(), key=lambda kv: (cw(kv), weight(*kv[0]), kv[0]))
        else:
            ordered = sorted(classes.items(), key=lambda kv: (weight(*kv[0]), cw(kv), kv[0]))
        for k, terms in ordered:
            seen.add(k)
            cm = max(abs(c) for c, _, _ in terms)
            G = PauliSum(n, [(c / cm, x, z) for c, x, z in terms])
            lab = _label(*k, n)
            layers.append(Layer(f"{name_prefix}{len(layers) + 1}:{lab}", G))
            entries.append(Entry(level, weight(*k), cm, k, len(G), lab))
            if len(layers) >= max_layers:
                break
        if len(layers) >= max_layers or level == max_levels:
            break
        C = commutator(H, commutator(H, C)).scale(-1)
        if not len(C):
            break
    return (layers, entries) if return_entries else layers
